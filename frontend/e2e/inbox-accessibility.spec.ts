import { expect, test } from '@playwright/test'

test('inbox supports keyboard navigation and 200 percent magnification', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/auth/login')
  await page.getByLabel('Email').fill('dr.kim@docere.demo')
  await page.getByLabel('Пароль', { exact: true }).fill('DemoPass123')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard\/doctor$/)
  await page.goto('/notifications')
  await expect(page.getByText('Проверяем входящие задачи…')).toHaveCount(0)
  await page.evaluate(() => { document.documentElement.style.zoom = '2' })
  await expect(page.getByRole('heading', { name: 'Входящие', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'События', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/tab=events/)
  await page.getByRole('checkbox', { name: 'Только непрочитанные' }).focus()
  await page.keyboard.press('Space')
  await expect(page).toHaveURL(/unread=true/)
  await expect(page.getByText('Загружаем события…')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('inbox-200-percent.png'), fullPage: true })
  await page.evaluate(() => { document.documentElement.style.zoom = '1' })
  await page.getByRole('button', { name: /^Входящие:/ }).click()
  await expect(page.getByText(/Непрочитанных событий:/)).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: /^Входящие:/ })).toBeFocused()
})
